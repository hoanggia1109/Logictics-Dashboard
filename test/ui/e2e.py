BOA = (10.7790, 106.7030)   # cách văn phòng ~330 m để FO "chạy" tới trong vài giây

fails, passes, errs, http4 = [], [0], [], []
# Các phản hồi lỗi mà kịch bản CỐ Ý gây ra (nhập sai mật khẩu, tên đăng nhập sai dạng, đăng nhập tài khoản bị khoá).
EXPECTED_4XX = {(401, 'POST', '/api/login'), (400, 'POST', '/api/users'), (403, 'POST', '/api/bo-link/view')}  # 403: máy thứ hai cố mở link của BO
def ok(cond, msg):
    if cond: passes[0] += 1
    else:
        fails.append(msg); print('    ✗ ' + msg)
def step(name): print('  • ' + name)

def start_server(data):
    env = dict(os.environ, PORT=str(PORT), DATA_DIR=data, TILE_URL='', DEMO='0', LEAD_PASS='Khoitao-12345')
    p = subprocess.Popen(['node', '--disable-warning=ExperimentalWarning', 'server.js'], cwd=ROOT, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    for _ in range(100):
        try:
            urllib.request.urlopen(BASE + '/healthz', timeout=1); return p
        except Exception: time.sleep(0.1)
    p.kill(); raise RuntimeError('máy chủ không khởi động được')

def main():
    data = tempfile.mkdtemp(prefix='arl-ui-')
    srv = start_server(data)
