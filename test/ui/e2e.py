            def dlg_ok(pg, label=None):
                d = dlg(pg)
                (d.locator('.dlg-foot button', has_text=label) if label else d.locator('.dlg-foot .primary')).click()
            def no_dlg(pg): pg.wait_for_selector('dialog.dlg', state='detached', timeout=8000)
            def toast(pg): return pg.inner_text('#toast') if pg.locator('#toast:not([hidden])').count() else ''
