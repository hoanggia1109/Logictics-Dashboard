#!/usr/bin/env python3
"""Kiểm thử giao diện đầu-cuối: dựng máy chủ sạch rồi cho Lead, FO, BO, Logistic thao tác như người thật trên Chromium.
Cần: pip install playwright && playwright install chromium.   Chạy: python3 test/ui/e2e.py
"""
import os, re, shutil, subprocess, sys, tempfile, time, urllib.request
from playwright.sync_api import sync_playwright

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PORT = 8093
BASE = f'http://localhost:{PORT}'
PHOTO = os.path.join(ROOT, 'test', 'fixtures', 'photo.jpg')
SHOTS = os.environ.get('SHOTS', '')
